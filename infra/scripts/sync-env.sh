#!/usr/bin/env bash
# Write /opt/nirby/<env>/.env from environment variables (called by CI/CD).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "${SCRIPT_DIR}/lib/common.sh"

ENV_NAME="$(normalize_env "${1:?usage: sync-env.sh <staging|prod>}")"
DEPLOY_DIR="$(deploy_dir_for_env "$ENV_NAME")"

mkdir -p "$DEPLOY_DIR"
chmod 700 "$DEPLOY_DIR"

required_vars=(
  JWT_SECRET
  DB_PASSWORD
  DB_APP_PASSWORD
  RESEND_API_KEY
  GOOGLE_PLACES_API_KEY
  FRONTEND_URL
  S3_BUCKET
  S3_REGION
  S3_ACCESS_KEY_ID
  S3_SECRET_ACCESS_KEY
  S3_PUBLIC_URL
)

for var in "${required_vars[@]}"; do
  if [[ -z "${!var:-}" ]]; then
    echo "ERROR: missing required environment variable ${var}" >&2
    exit 1
  fi
done

# Preserve pinned SHAs when only one service is deployed (e.g. web-only CI job).
DEPLOY_API_SHA="${DEPLOY_API_SHA:-$(read_deployed_sha "$DEPLOY_DIR" api)}"
DEPLOY_WEB_SHA="${DEPLOY_WEB_SHA:-$(read_deployed_sha "$DEPLOY_DIR" web)}"

cat >"${DEPLOY_DIR}/.env" <<EOF
# Generated by sync-env.sh — do not commit.
JWT_SECRET=${JWT_SECRET}
DB_PASSWORD=${DB_PASSWORD}
DB_APP_PASSWORD=${DB_APP_PASSWORD}
RESEND_API_KEY=${RESEND_API_KEY}
GOOGLE_PLACES_API_KEY=${GOOGLE_PLACES_API_KEY}
FRONTEND_URL=${FRONTEND_URL}
EMAIL_VERIFICATION_TEMPLATE_ID_EN=${EMAIL_VERIFICATION_TEMPLATE_ID_EN:-}
EMAIL_VERIFICATION_TEMPLATE_ID_FR=${EMAIL_VERIFICATION_TEMPLATE_ID_FR:-}
EMAIL_PASSWORD_RESET_TEMPLATE_ID_EN=${EMAIL_PASSWORD_RESET_TEMPLATE_ID_EN:-}
EMAIL_PASSWORD_RESET_TEMPLATE_ID_FR=${EMAIL_PASSWORD_RESET_TEMPLATE_ID_FR:-}
EMAIL_ACCOUNT_DELETED_TEMPLATE_ID_EN=${EMAIL_ACCOUNT_DELETED_TEMPLATE_ID_EN:-}
EMAIL_ACCOUNT_DELETED_TEMPLATE_ID_FR=${EMAIL_ACCOUNT_DELETED_TEMPLATE_ID_FR:-}
EMAIL_COLLABORATOR_INVITE_TEMPLATE_ID_EN=${EMAIL_COLLABORATOR_INVITE_TEMPLATE_ID_EN:-}
EMAIL_COLLABORATOR_INVITE_TEMPLATE_ID_FR=${EMAIL_COLLABORATOR_INVITE_TEMPLATE_ID_FR:-}
S3_BUCKET=${S3_BUCKET}
S3_REGION=${S3_REGION}
S3_ACCESS_KEY_ID=${S3_ACCESS_KEY_ID}
S3_SECRET_ACCESS_KEY=${S3_SECRET_ACCESS_KEY}
S3_PUBLIC_URL=${S3_PUBLIC_URL}
SENTRY_DSN=${SENTRY_DSN:-}
DEPLOY_API_SHA=${DEPLOY_API_SHA}
DEPLOY_WEB_SHA=${DEPLOY_WEB_SHA}
BACKUP_POLICY=${BACKUP_POLICY:-always}
KEEP_IMAGES=${KEEP_IMAGES:-5}
EOF

chmod 600 "${DEPLOY_DIR}/.env"
log "Wrote ${DEPLOY_DIR}/.env"
